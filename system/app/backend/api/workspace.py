"""Paths of project-owned files under the workspace root (implementation plan WP2.4, NFR-08).

Every path is built from canonical UUIDs generated by the application and an allow-listed suffix. Nothing a user
typed (file name, dataset name, header) ever becomes part of a path; the original file name is display metadata only.
The database stores the path relative to the root, so the database and the workspace directory can be moved together.
"""
from __future__ import annotations

import re
import shutil
import uuid
from pathlib import Path

SUFFIXES = frozenset({'.csv', '.tsv'})
_STORED = re.compile(r'^(?P<project>[0-9a-f-]{36})/(?P<dataset>[0-9a-f-]{36})(?P<suffix>\.csv|\.tsv)$')


class WorkspacePathError(ValueError):
    """An identifier or stored path that the application did not generate."""


def canonical_uuid(value: str) -> str:
    try:
        canon = str(uuid.UUID(value))
    except (ValueError, AttributeError, TypeError) as exc:
        raise WorkspacePathError('not a UUID') from exc
    if canon != value:                       # reject braces, upper case, urn: prefixes and other spellings
        raise WorkspacePathError('not a canonical UUID')
    return canon


def _inside(root: Path, path: Path) -> Path:
    root = root.resolve()
    resolved = path.resolve()
    if resolved.parent != root and root not in resolved.parents:
        raise WorkspacePathError('path escapes the workspace root')
    return resolved


def project_dir(root: Path, project_id: str) -> Path:
    return _inside(root, Path(root) / canonical_uuid(project_id))


def dataset_relpath(project_id: str, dataset_id: str, suffix: str) -> str:
    if suffix not in SUFFIXES:
        raise WorkspacePathError('unsupported file type')
    return f'{canonical_uuid(project_id)}/{canonical_uuid(dataset_id)}{suffix}'


def resolve_stored(root: Path, relpath: str) -> Path:
    """Turn a stored relative path back into an absolute one, refusing anything the application could not have written."""
    m = _STORED.match(relpath)
    if not m:
        raise WorkspacePathError('stored path has an unexpected form')
    canonical_uuid(m['project'])
    canonical_uuid(m['dataset'])
    return _inside(root, Path(root) / relpath)


def remove_project_dir(root: Path, project_id: str) -> str | None:
    """Delete a project's directory. Returns None on success (or when it never existed), else the error text, so the
    caller can report the cleanup as incomplete and retry it (FR-33, NFR-10)."""
    path = project_dir(root, project_id)
    if not path.exists():
        return None
    try:
        shutil.rmtree(path)
    except OSError as exc:
        return f'{type(exc).__name__}: {exc.strerror or exc}'
    return None
