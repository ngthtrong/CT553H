"""Copy the importer into a development-plugin folder with a real assigned ID.

Usage: python3 configure_plugin.py /path/to/figma-created/manifest.json
The target manifest must be one generated by Figma's Create new plugin dialog.
"""
from pathlib import Path
import argparse
import json
import shutil

def main():
    parser=argparse.ArgumentParser();parser.add_argument('manifest',type=Path);args=parser.parse_args()
    target=args.manifest.expanduser().resolve();data=json.loads(target.read_text())
    plugin_id=data.get('id','')
    if not isinstance(plugin_id,str) or not plugin_id.isdigit():
        raise SystemExit('Use the manifest generated by Figma with its assigned numeric plugin ID; do not invent one.')
    here=Path(__file__).resolve().parent.parent
    code=here/'figma-plugin/code.js'
    if not code.exists():raise SystemExit('code.js is missing. Keep this script with the extracted package.')
    if code.resolve()!=(target.parent/'code.js').resolve():
        shutil.copy2(code,target.parent/'code.js')
    data.update(name='Degron Footprint UX/UI Import',api='1.0.0',editorType=['figma'],main='code.js',documentAccess='dynamic-page',networkAccess={'allowedDomains':['none']})
    data.pop('ui',None)
    target.write_text(json.dumps(data,indent=2)+'\n')
    print('Configured:',target,'\nOpen the intended Figma Design file and run the development plugin once.')

if __name__=='__main__':main()
