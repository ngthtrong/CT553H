# ---------------------------------------------------------------- formatting
def f4(x):
    return f'{x:.4f}'

def sg(x, d=4):
    return ('+' if x >= 0 else '$-$') + f'{abs(x):.{d}f}'

def ci(c):
    return f'[{sg(c[0])}, {sg(c[1])}]'

def dci(d):
    return f'{sg(d["delta"])} {ci(d["ci95"])}'

def src(*files):
    # Internal provenance is metadata, not a file-path citation in the printed thesis.
    return '% Internal provenance (not printed): ' + ', '.join(files)

def table(name, spec, head, rows, files, size=r'\small', tabsep=None):
    lines = [r'\begingroup' + size + (r'\setlength{\tabcolsep}{%s}' % tabsep if tabsep else ''), r'\renewcommand{\arraystretch}{1.15}',
             r'\begin{tabularx}{\textwidth}{' + spec.replace('X', r'>{\raggedright\arraybackslash}X') + '}', r'\toprule',
             ' & '.join(head) + r' \\', r'\midrule']
    for r in rows:
        lines.append(r[0] if r == [MID] else ' & '.join(r) + r' \\')
    lines += [r'\bottomrule', r'\end{tabularx}', src(*files), r'\endgroup']
    (HERE / f'{name}.tex').write_text('% Generated by build_ch4_assets.py - do not edit.\n' + '\n'.join(lines) + '\n')

