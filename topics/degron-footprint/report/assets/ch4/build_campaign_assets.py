def f(v, digits=4):
    return '--' if v is None else f'{v:.{digits}f}'


def ci(values):
    return '['+f(values[0])+', '+f(values[1])+']'


def label(name):
    names = {'esm2_8m': 'ESM2-8M', 'esm2_35m': 'ESM2-35M', 'esm2_150m': 'ESM2-150M',
             'esm2_650m': 'ESM2-650M', 'esm1b_650m': 'ESM1b-650M',
             'esm1v_650m_1': 'ESM1v-650M', 'esmc_300m': 'ESM-C-300M',
             'prott5_encoder': 'ProtT5', 'ankh_base': 'Ankh-base'}
    for old in sorted(names, key=len, reverse=True):
        name = name.replace(old, names[old])
    return name.replace('_', ' ').replace('nested-family-selection', 'Nested family').replace('dpsi rep12 mean', 'mean12').replace('dpsi rep1', 'rep1')


def tex(s):
    return str(s).replace('&', r'\&').replace('%', r'\%').replace('_', r'\_').replace('-', r'-\allowbreak{}')


def table(name, headers, rows, spec=None):
    spec = spec or 'l'+'r'*(len(headers)-1)
    lines = [PROVENANCE, r'{\small\setlength{\tabcolsep}{4pt}',
             r'\begin{tabularx}{\textwidth}{'+spec+'}', r'\toprule',
             ' & '.join(headers)+r' \\', r'\midrule']
    lines += [' & '.join(map(str, row))+r' \\' for row in rows]
    lines += [r'\bottomrule', r'\end{tabularx}}', '']
    (HERE / (name+'.tex')).write_text('\n'.join(lines), encoding='utf-8')


