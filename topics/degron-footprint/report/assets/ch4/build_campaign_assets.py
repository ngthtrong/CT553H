def diagram(name,nodes,edges,width,height):
    root=ET.Element('mxfile',host='app.diagrams.net',version='32.6.10')
    graph=ET.SubElement(ET.SubElement(root,'diagram',id=name,name=name),'mxGraphModel',
                        dx=str(width),dy=str(height),grid='1',gridSize='10',page='1',pageWidth=str(width),pageHeight=str(height),background='#ffffff')
    cells=ET.SubElement(graph,'root'); ET.SubElement(cells,'mxCell',id='0'); ET.SubElement(cells,'mxCell',id='1',parent='0')
    colors={'blue':('#E8F2F8',BLUE),'orange':('#FFF1E6',ORANGE),'green':('#E7F5EF',GREEN),'gray':('#F3F4F5',GRAY)}
    for ident,text,x,y,w,h,color in nodes:
        fill,stroke=colors[color]
        cell=ET.SubElement(cells,'mxCell',id=ident,value=text,vertex='1',parent='1',
            style=f'rounded=1;whiteSpace=wrap;html=0;align=center;verticalAlign=middle;fontFamily=Times New Roman;fontSize=20;spacing=10;fillColor={fill};strokeColor={stroke};strokeWidth=2;')
        ET.SubElement(cell,'mxGeometry',x=str(x),y=str(y),width=str(w),height=str(h),attrib={'as':'geometry'})
    for index,(source,target,ports,points) in enumerate(edges):
        cell=ET.SubElement(cells,'mxCell',id=f'flow-{index}',source=source,target=target,edge='1',parent='1',
          style='edgeStyle=orthogonalEdgeStyle;rounded=1;orthogonalLoop=1;jettySize=auto;html=0;endArrow=block;endFill=1;strokeColor=#444444;strokeWidth=2;'+ports)
        geo=ET.SubElement(cell,'mxGeometry',relative='1',attrib={'as':'geometry'})
        if points:
            arr=ET.SubElement(geo,'Array',attrib={'as':'points'})
            for x,y in points:
                ET.SubElement(arr,'mxPoint',x=str(x),y=str(y))
    ET.indent(root)
    ET.ElementTree(root).write(DIAGRAM/(name+'.drawio'),encoding='utf-8',xml_declaration=True)

