"""Render descriptive error diagnostics from independently checked saved OOF.

No fitting and no new confidence intervals. Source hashes are retained in the
generated TeX comments; the report describes populations instead of file paths.
"""
from pathlib import Path
import hashlib
import json

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib import font_manager
import numpy as np

HERE = Path(__file__).resolve().parent
TOPIC = next(p for p in HERE.parents if (p / 'data/README.md').exists())
SOURCE = TOPIC / 'research/progress-review-2026-11-06/local-audit.json'
D = json.loads(SOURCE.read_text())
HEADER = ('% Generated by build_progress_assets.py; descriptive OOF diagnostics.\n'
          '% Source: research/progress-review-2026-11-06/local-audit.json\n'
          '% SHA256: ' + hashlib.sha256(SOURCE.read_bytes()).hexdigest() + '\n')
try:
    font_manager.findfont('Times New Roman', fallback_to_default=False)
except ValueError:
    for name in ['times.ttf', 'timesbd.ttf', 'timesi.ttf', 'timesbi.ttf']:
        path = Path('/mnt/c/Windows/Fonts') / name
        if path.is_file():
            font_manager.fontManager.addfont(str(path))
    font_manager.findfont('Times New Roman', fallback_to_default=False)
plt.rcParams.update({'font.family': 'serif', 'font.serif': ['Times New Roman'],
    'font.size': 11, 'axes.spines.top': False, 'axes.spines.right': False,
    'pdf.fonttype': 42, 'ps.fonttype': 42, 'savefig.facecolor': 'white'})


def tex(value):
    return str(value).replace('_', r'\_')


def write(name, content):
    (HERE / name).write_text(HEADER + content + '\n')


fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.65), layout='constrained')
maximum = max(r[k] for arm in ['B', 'D']
              for r in D['matched_lora_minus_frozen'][arm]['per_peptide']
              for k in ['mae_lora', 'mae_frozen'])
upper = np.ceil(maximum * 10) / 10 + .05
for ax, arm, color in zip(axes, ['B', 'D'], ['#0072B2', '#D55E00']):
    rows = D['matched_lora_minus_frozen'][arm]['per_peptide']
    assert len(rows) == 235 and len({r['peptide_id'] for r in rows}) == 235
    ax.scatter([r['mae_frozen'] for r in rows], [r['mae_lora'] for r in rows],
               s=17, color=color, alpha=.72, linewidths=.2, edgecolors='white')
    ax.plot([0, upper], [0, upper], color='#333333', lw=1, ls='--')
    ax.set(xlim=(0, upper), ylim=(0, upper), aspect='equal',
           xlabel='Frozen MAE (PSI)', ylabel='LoRA MAE (PSI)', title=f'Arm {arm}: 235 peptides')
    c = D['matched_lora_minus_frozen'][arm]
    ax.text(.04, .96, f"Lower MAE: {c['peptides_improved']}\nHigher MAE: {c['peptides_worsened']}",
            transform=ax.transAxes, va='top', fontsize=10)
    ax.grid(alpha=.18, linewidth=.5)
fig.savefig(HERE / 'fig-progress-residuals.pdf')
fig.savefig(HERE / 'fig-progress-residuals.png', dpi=200)
plt.close(fig)

recipes = ['esm2_35m-frozen-B', 'esm2_35m-lora-B', 'esm2_35m-frozen-D', 'esm2_35m-lora-D']
classes = [('neutral', r'$-1<\Delta<1$'), ('positive_ge1', r'$\Delta\ge1$'),
           ('negative_le-1', r'$\Delta\le-1$')]
rows = [r'{\small\setlength{\tabcolsep}{3.5pt}',
        r'\begin{tabularx}{\textwidth}{Xrrrrrrr}', r'\toprule',
        r'Effect & Cells & Pep./grp. & Fr.-B & LoRA-B & Fr.-D & LoRA-D & Zero \\', r'\midrule']
for key, label in classes:
    values = [next(v for v in D['core_diagnostics'][r]['per_effect_class'] if v['effect_class'] == key) for r in recipes]
    a = values[0]
    assert all((v['cells'], v['peptides'], v['groups']) == (a['cells'], a['peptides'], a['groups']) for v in values)
    rows.append(' & '.join([label, f"{a['cells']:,}", f"{a['peptides']}/{a['groups']}"] +
                           [f"{v['mae']:.4f}" for v in values] + [f"{a['zero_mae']:.4f}"]) + r' \\')
rows.extend([r'\bottomrule', r'\end{tabularx}}'])
write('tab-progress-effect-errors.tex', '\n'.join(rows))

worst = D['core_diagnostics']['esm2_35m-lora-B']['largest_cell_errors'][:3]
rows = [r'{\small\setlength{\tabcolsep}{4pt}', r'\begin{tabularx}{\textwidth}{Xrrrrr}',
        r'\toprule', r'Peptide & Fold & Position & Change & Measured & Predicted \\', r'\midrule']
for r in worst:
    rows.append(' & '.join([tex(r['peptide_id']), str(r['outer_fold']), str(r['position_1based']),
         f"{r['wt_aa']}$\\to${r['mut_aa']}", f"{r['dpsi_mean']:.4f}", f"{r['prediction']:.4f}"]) + r' \\')
rows.extend([r'\bottomrule', r'\end{tabularx}}'])
write('tab-progress-largest-errors.tex', '\n'.join(rows))

numbers = []
for arm in ['B', 'D']:
    c = D['matched_lora_minus_frozen'][arm]
    for key, suffix in [('peptides_improved', 'PepBetter'), ('peptides_worsened', 'PepWorse'),
                        ('groups_improved', 'GrpBetter'), ('groups_worsened', 'GrpWorse')]:
        numbers.append(r'\newcommand{\nProgress' + arm + suffix + '}{' + str(c[key]) + '}')
    lo, hi = c['leave_one_group_out_delta_range']
    numbers.append(r'\newcommand{\nProgress' + arm + 'LeaveGroup}{' + f'[{lo:.4f}, {hi:.4f}]' + '}')
write('progress-numbers.tex', '\n'.join(numbers))
print('Generated descriptive residual figure, 2 tables and numeric macros from verified OOF audit.')
