STATUS = dict(CONTRACT['x_implementation_status'])
if STATUS.get('planned', 0):
    raise SystemExit(f'contract snapshot still has planned operations: {STATUS}')
N_PATHS, N_OPERATIONS = CONTRACT['paths'], CONTRACT['operations']
