unplaced = sorted(set(BY_NAME) - {n for names in GROUPS.values() for n in names})
if unplaced:
    raise SystemExit(f'tables missing from the printed grouping: {unplaced}')

rows = []
for group, names in GROUPS.items():
    for name in names:
        t = BY_NAME[name]
        fks = ', '.join(sorted({fk['target'].split('.')[0] for fk in t['foreign_keys']})) or '--'
        cascade = sum(1 for fk in t['foreign_keys'] if fk['ondelete'] == 'CASCADE')
        rows.append([tex(name), SHORT[group], t['columns'],
                     tex('+'.join(t['primary_key'])).replace(r'\_', r'\_\allowbreak{}'),
                     len(t['foreign_keys']), f"{cascade}", len(t['unique']), t['checks'],
                     len(t['indexes']), t['created_in'].split('_')[0]])
