"""Render the measured equal-budget replay; no fitting or metric recomputation.

Provenance belongs in comments/metadata, never printed as thesis evidence.
Run: .venv/bin/python -I report/assets/ch4/build_prioritization_assets.py
"""
import csv
import hashlib
import json
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib import font_manager

HERE = Path(__file__).resolve().parent
ROOT = next(p for p in HERE.parents if (p/'CLAUDE.md').exists())
SOURCE = ROOT/'research/oof-prioritization-2026-11-07'
INPUTS = ['results.json','summary.csv','strata.csv','budget-curves.csv',
          'random-reference.csv','independent-validation.json','config.json']
MANIFEST = json.loads((SOURCE/'artifact-manifest.json').read_text())
SOURCES = {}
for name in INPUTS:
    content = (SOURCE/name).read_bytes()
    digest = hashlib.sha256(content).hexdigest()
    assert digest == MANIFEST['files'][name]['sha256'], name
    SOURCES[name] = dict(bytes=len(content), sha256=digest)
D = json.loads((SOURCE/'results.json').read_text())
assert D['cohort'] == dict(cells=122412,peptides=235,groups=221)
assert json.loads((SOURCE/'independent-validation.json').read_text())['status']=='pass'
HEADER = ('% Generated by build_prioritization_assets.py; retrospective development OOF.\n'
          '% Source: research/oof-prioritization-2026-11-07/results.json\n'
          '% SHA256: '+SOURCES['results.json']['sha256']+'\n')
OUTPUTS = []


def read_csv(name):
    with (SOURCE/name).open() as stream:
        return list(csv.DictReader(stream))


def write(name, content):
    (HERE/name).write_text(HEADER+content+'\n')
    OUTPUTS.append(name)


def table(name, columns, header, rows, font=r'\small'):
    content = ['{'+font+r'\setlength{\tabcolsep}{4pt}',
               r'\begin{tabularx}{\textwidth}{'+columns+'}',r'\toprule',
               ' & '.join(header)+r' \\',r'\midrule']
    content += [' & '.join(row)+r' \\' for row in rows]
    content += [r'\bottomrule',r'\end{tabularx}}']
    write(name,'\n'.join(content))


def percent(x):
    return f'{100*float(x):.2f}'


def interval(values, multiplier=1):
    return '$['+f'{multiplier*values[0]:.2f}, {multiplier*values[1]:.2f}'+']$'


PRIMARY = {row['policy']:row for row in D['primary_summary']}
SUMMARY = read_csv('summary.csv')
NAMES = {'lora-D':'LoRA-D','ridge-w5-D':'Ridge W5-D','random':'Random expectation',
         'frozen-D':'Frozen-D','lora-B':'LoRA-B'}
ORDER = ['lora-D','ridge-w5-D','random','frozen-D','lora-B']
NEGATIVE = {row['policy']:row for row in SUMMARY if row['direction']=='minus'
            and row['budget']=='k10' and row['prediction_set']=='ensemble'}
table('tab-priority-main.tex','Xrrrr',
      ['Policy','P@10 (+)','Hits (+)','R@10 (+)','P@10 ($-$)'],[
      [NAMES[name],percent(PRIMARY[name]['precision']),
       f"{PRIMARY[name]['hits_total']:.2f}" if name=='random' else f"{int(PRIMARY[name]['hits_total']):,}",
       percent(PRIMARY[name]['recall']),percent(NEGATIVE[name]['precision'])] for name in ORDER])
table('tab-priority-contrasts.tex','Xrrr',
      ['LoRA-D minus','Difference (pp)',r'95\% CI',r'97.5\% CI'],[
      [NAMES[row['baseline']],f"{100*row['delta']:+.2f}",interval(row['ci95'],100),
       interval(row['ci_adjusted'],100)] for row in D['primary_contrasts']])
table('tab-priority-recall-budget.tex','Xrr',
      ['Policy',r'50\% hit recall',r'80\% hit recall'],[
      [NAMES[name],f"{PRIMARY[name]['btr50']:.2f}",f"{PRIMARY[name]['btr80']:.2f}"]
      for name in ['lora-D','ridge-w5-D','random']])
STRATA = read_csv('strata.csv')
STRATA_LABELS = {'le3':r'$\le3$','gt3_le4':r'$(3,4]$',
                 'gt4_le5':r'$(4,5]$','gt5':r'$>5$'}
strata_rows=[]
for value,label in STRATA_LABELS.items():
    selected={row['policy']:row for row in STRATA if row['stratum']=='psi_stratum'
              and row['value']==value and row['direction']=='plus'}
    strata_rows.append([label,selected['lora-D']['peptides'],
                        selected['lora-D']['no_hit_peptides'],
                        percent(selected['lora-D']['precision']),
                        percent(selected['ridge-w5-D']['precision'])])
table('tab-priority-strata.tex','Xrrrr',
      ['WT PSI','Peptides','No (+) hit','LoRA-D P@10','W5-D P@10'],strata_rows)
table('tab-priority-seeds.tex','Xrrrr',
      ['Policy','Seed 17','Seed 29','Seed 43','Ensemble'],[
      [NAMES[name],*[percent(next(row for row in D['per_seed_primary']
          if row['policy']==name and row['prediction_set']==f'seed{s}')['precision'])
          for s in [17,29,43]],percent(PRIMARY[name]['precision'])]
      for name in ORDER if name!='random'])
budget_rows=[]
for budget,label in [('k5','$k=5$'),('k10','$k=10$'),('k20','$k=20$'),
                     ('q05',r'Top 5\%'),('q10',r'Top 10\%'),('q20',r'Top 20\%')]:
    selected={row['policy']:row for row in SUMMARY if row['budget']==budget
              and row['prediction_set']=='ensemble' and row['direction']=='plus'}
    assert len({row['budget_total'] for row in selected.values()})==1
    budget_rows.append([label,f"{int(selected['lora-D']['budget_total']):,}",
                        *[percent(selected[name]['precision']) for name in ORDER]])
table('tab-priority-budgets.tex','Xrrrrrr',
      ['Budget','Total','LoRA-D','W5-D','Random','Frozen-D','LoRA-B'],budget_rows,
      font=r'\footnotesize')

contrast = {row['baseline']:row for row in D['primary_contrasts']}
numbers = {
    'Selections':'2,350','LoraPrecision':percent(PRIMARY['lora-D']['precision']),
    'WfivePrecision':percent(PRIMARY['ridge-w5-D']['precision']),
    'RandomPrecision':percent(PRIMARY['random']['precision']),
    'LoraHits':f"{int(PRIMARY['lora-D']['hits_total']):,}",
    'WfiveHits':f"{int(PRIMARY['ridge-w5-D']['hits_total']):,}",
    'RandomHits':f"{PRIMARY['random']['hits_total']:.2f}",
    'DeltaWfive':percent(contrast['ridge-w5-D']['delta']),
    'DeltaRandom':percent(contrast['random']['delta']),
    'WfiveCI':'['+', '.join(f'{100*x:.2f}' for x in contrast['ridge-w5-D']['ci_adjusted'])+']',
    'RandomCI':'['+', '.join(f'{100*x:.2f}' for x in contrast['random']['ci_adjusted'])+']',
    'ExtraHits':str(int(contrast['ridge-w5-D']['delta_total_hits'])),
    'LoraRecall':percent(PRIMARY['lora-D']['recall']),
    'LoraBtrFifty':f"{PRIMARY['lora-D']['btr50']:.2f}",
    'WfiveBtrFifty':f"{PRIMARY['ridge-w5-D']['btr50']:.2f}",
    'RandomBtrFifty':f"{PRIMARY['random']['btr50']:.2f}",
    'LoraNegativePrecision':percent(NEGATIVE['lora-D']['precision']),
    'NoCutoffTies':str(max(row['cutoff_tie_peptides'] for row in D['tie_sensitivity'])),
}
write('priority-numbers.tex','\n'.join(r'\newcommand{\nPriority'+key+'}{'+value+'}'
                                     for key,value in numbers.items()))

try:
    font_manager.findfont('Times New Roman', fallback_to_default=False)
except ValueError:
    for name in ['times.ttf','timesbd.ttf','timesi.ttf','timesbi.ttf']:
        path=Path('/mnt/c/Windows/Fonts')/name
        if path.is_file(): font_manager.fontManager.addfont(str(path))
    font_manager.findfont('Times New Roman',fallback_to_default=False)
plt.rcParams.update({'font.family':'serif','font.serif':['Times New Roman'],
                     'font.size':10,'axes.spines.top':False,'axes.spines.right':False,
                     'pdf.fonttype':42,'savefig.facecolor':'white'})
curve=read_csv('budget-curves.csv');random=read_csv('random-reference.csv')
colors={'lora-D':'#0072B2','ridge-w5-D':'#D55E00','random':'#555555',
        'frozen-D':'#009E73','lora-B':'#CC79A7'}
fig,axes=plt.subplots(1,2,figsize=(7.2,3.35),layout='constrained')
for ax,metric in zip(axes,['hits','recall']):
    for name in ORDER:
        selected=sorted([row for row in curve if row['policy']==name and row['direction']=='plus'
                         and row['metric']==metric],key=lambda row:int(row['budget_k']))
        xs=[int(row['budget_k']) for row in selected]
        ax.plot(xs,[float(row['mean']) for row in selected],color=colors[name],
                lw=1.55,label=NAMES[name])
        if name in ['lora-D','ridge-w5-D']:
            ax.fill_between(xs,[float(row['cluster_ci95_low']) for row in selected],
                            [float(row['cluster_ci95_high']) for row in selected],
                            color=colors[name],alpha=.11)
    selected=sorted([row for row in random if row['direction']=='plus' and row['metric']==metric],
                    key=lambda row:int(row['budget_k']))
    ax.fill_between([int(row['budget_k']) for row in selected],
                    [float(row['conditional_q025']) for row in selected],
                    [float(row['conditional_q975']) for row in selected],color='#777777',alpha=.25)
    ax.set_xscale('log');ax.set_xlabel('Selections per peptide (log scale)')
    ax.set_ylabel('Mean hits per peptide' if metric=='hits' else 'Mean recall (peptides with hits)')
    ax.grid(alpha=.18)
axes[0].legend(fontsize=8,frameon=False,loc='upper left')
axes[1].set_ylim(0,1.03)
for extension in ['pdf','png']:
    name='fig-priority-budget.'+extension
    fig.savefig(HERE/name,dpi=200)
    OUTPUTS.append(name)
plt.close(fig)
manifest=dict(source_directory=SOURCE.relative_to(ROOT).as_posix(),sources=SOURCES,
              generated={name:dict(bytes=(HERE/name).stat().st_size,
                sha256=hashlib.sha256((HERE/name).read_bytes()).hexdigest()) for name in OUTPUTS},
              generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              scope='Render existing verified retrospective metrics; no training, inference or bootstrap rerun.')
(HERE/'priority-assets.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Rendered',len(OUTPUTS),'prioritization assets from hash-verified sources.')
