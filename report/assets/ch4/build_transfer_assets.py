"""Generate the branch-1 refit/transfer tables, figures and macros.

Sources are the locked result files of campaign aa4fc2b7ce29abf9 and the D-4
decision record. No metric is recomputed here: every number is read from a
result file and only formatted. The script fails loudly if a source changes
shape, so a stale asset cannot be printed silently.
"""
from pathlib import Path
import hashlib
import json

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
REPORT = HERE.parents[1]
TOPIC = next(p for p in HERE.parents if (p / 'data/README.md').exists())
REFIT = TOPIC / 'research/lora-refit-transfer-2026-11-16'
DECISION = TOPIC / 'research/g2-acceptance-2026-11-07/d4-decision-2026-11-17.md'
LATENCY = TOPIC / 'system/app/tests/results/latency-lora.json'

SOURCES = {
    'results': REFIT / 'results.json',
    'errors': REFIT / 'error-results.json',
    'similarity': REFIT / 'similarity-results.json',
    'koren': REFIT / 'koren-results.json',
    'card': REFIT / 'model-card.json',
    'decision': DECISION,
    'latency': LATENCY,
}
for key, path in SOURCES.items():
    if not path.exists():
        raise SystemExit(f'missing source: {key} -> {path}')

R = json.loads(SOURCES['results'].read_text(encoding='utf-8'))
E = json.loads(SOURCES['errors'].read_text(encoding='utf-8'))
S = json.loads(SOURCES['similarity'].read_text(encoding='utf-8'))
K = json.loads(SOURCES['koren'].read_text(encoding='utf-8'))
C = json.loads(SOURCES['card'].read_text(encoding='utf-8'))
L = json.loads(SOURCES['latency'].read_text(encoding='utf-8'))

if R['scientific_status'] != 'development_not_gate_closure':
    raise SystemExit('refusing to build: results.json no longer says development_not_gate_closure')
if C['serving_promotion'] != 'not_authorized_by_research_execution':
    raise SystemExit('refusing to build: model card no longer withholds serving promotion')

PROVENANCE = ('% Generated by build_transfer_assets.py\n'
              + ''.join(f'% {k}: {SOURCES[k].relative_to(TOPIC)} sha256 '
                        f'{hashlib.sha256(SOURCES[k].read_bytes()).hexdigest()}\n'
                        for k in ('results', 'errors', 'similarity', 'koren', 'card', 'decision', 'latency')))

BLUE, ORANGE, GREEN, GRAY = '#0072B2', '#D55E00', '#009E73', '#666666'
plt.rcParams.update({'font.family': 'serif', 'font.serif': ['Times New Roman'],
                     'font.size': 13, 'axes.spines.top': False, 'axes.spines.right': False,
                     'pdf.fonttype': 42, 'ps.fonttype': 42, 'savefig.facecolor': 'white'})

LORA, FROZEN, W5, ZERO, CONST = ('esm2_35m-lora-D', 'esm2_35m-frozen-D',
                                 'ordered-w5-D', 'zero', 'constant-W-mean')
NAMES = {LORA: 'LoRA-D', FROZEN: 'Frozen-D', W5: 'W5-D ridge',
         ZERO: 'Zero predictor', CONST: 'Constant (W mean)'}
STRATA = [('le3', r'$\le 3$'), ('gt3_le4', r'$3<\mathrm{PSI}\le4$'),
          ('gt4_le5', r'$4<\mathrm{PSI}\le5$'), ('gt5', r'$>5$')]
CON_FROZEN = f'{LORA}_minus_{FROZEN}'
CON_W5 = f'{LORA}_minus_{W5}'


def f(v, digits=4):
    return '--' if v is None else f'{v:.{digits}f}'


def ci(values, digits=4):
    return '[' + f(values[0], digits) + ', ' + f(values[1], digits) + ']'


def table(name, headers, rows, spec=None, small=True):
    spec = spec or 'l' + 'r' * (len(headers) - 1)
    body = [PROVENANCE]
    if small:
        body.append(r'{\small\setlength{\tabcolsep}{4pt}')
    body += [r'\begin{tabularx}{\textwidth}{' + spec + '}', r'\toprule',
             ' & '.join(headers) + r' \\', r'\midrule']
    body += [' & '.join(map(str, row)) + r' \\' for row in rows]
    body += [r'\bottomrule', r'\end{tabularx}' + ('}' if small else ''), '']
    (HERE / (name + '.tex')).write_text('\n'.join(body), encoding='utf-8')


# ---------------------------------------------------------------- main table
m = R['metrics']
rows = []
for key in (LORA, FROZEN, W5, ZERO, CONST):
    a = m[key]['all']
    prob = R['probability_metrics'].get(key, {})
    rows.append([NAMES[key], f(a['mae']), f(a['rmse']), f(a['spearman']),
                 f(a['auroc_plus']), f(prob.get('brier_three_class'))])
table('tab-transfer-main',
      ['Model', 'MAE', 'RMSE', 'Spearman', r'AUROC$+$', 'Brier'],
      rows, spec='Xrrrrr')

# ----------------------------------------------------------- contrasts table
rows = []
for key, shown in ((CON_FROZEN, 'LoRA-D minus frozen-D'), (CON_W5, 'LoRA-D minus W5-D')):
    c = R['contrasts'][key]
    rows.append([shown, f(c['delta']), ci(c['ci95']), ci(c['ci_adjusted'])])
table('tab-transfer-contrasts',
      ['Contrast', r'$\Delta$MAE', '95\\% interval', 'Adjusted interval'],
      rows, spec='Xrll')

# -------------------------------------------------------------- strata table
rows = []
for key, shown in STRATA:
    st = {name: m[name]['strata'][key] for name in (ZERO, W5, FROZEN, LORA)}
    sim = S['strata_lora_minus_zero'][key]
    rows.append([shown, st[ZERO]['peptides'], f(st[ZERO]['mae']), f(st[W5]['mae']),
                 f(st[FROZEN]['mae']), f(st[LORA]['mae']),
                 f(sim['delta']), ci(sim['ci_adjusted'])])
table('tab-transfer-strata',
      [r'WT PSI', '$n$', 'Zero', 'W5-D', 'Frozen-D', 'LoRA-D',
       r'$\Delta$', 'Adjusted interval'],
      rows, spec='lrrrrrrl')

# ---------------------------------------------------------- similarity table
rows = []
for key, shown in ((CON_FROZEN, 'LoRA-D minus frozen-D'), (CON_W5, 'LoRA-D minus W5-D')):
    for bin_name, b in S['contrasts'][key]['bins'].items():
        rows.append([shown, bin_name.replace('[', '[').replace(')', ')'),
                     b['peptides'], b['clusters'], f(b['delta']), ci(b['ci_adjusted'])])
table('tab-transfer-similarity',
      ['Contrast', 'Identity bin', 'Peptides', 'Groups', r'$\Delta$MAE', 'Adjusted interval'],
      rows, spec='Xlrrrl')

# --------------------------------------------------------------- Koren table
rows = []
for s in K['substrates']:
    rows.append([s['substrate'].replace('#', r'\#'), s['length'], s['mutants'],
                 f(s['lora']['ensemble_spearman'], 3), f(s['frozen']['ensemble_spearman'], 3)])
table('tab-transfer-koren',
      ['Substrate', 'Length', 'Mutants', 'LoRA-D $\\rho$', 'Frozen-D $\\rho$'],
      rows, spec='Xrrrr')

# ------------------------------------------------------- limitations L1--L10
# English renderings of the limitations recorded with the D-4 decision. The
# decision record is the authority; the assertion below fails the build if its
# list of identifiers ever changes.
import re
recorded = [cell for cell in
            (line.split('|')[1].strip() for line in
             SOURCES['decision'].read_text(encoding='utf-8').splitlines()
             if line.startswith('|') and line.count('|') >= 4)
            if re.fullmatch(r'L\d+', cell)]
expected = [f'L{i}' for i in range(1, 11)]
if recorded != expected:
    raise SystemExit(f'decision record limitation ids changed: {recorded}')

LIMITS = [
    ('L1', 'T was examined in earlier work, so this is a post-hoc transfer evaluation on a '
           'held-out source, not independent external validation.'),
    ('L2', 'The bootstrap conditions on the fitted predictions and excludes training and '
           'model-selection uncertainty. The three seeds share one outer partition.'),
    ('L3', 'In the WT-PSI $>5$ stratum the zero predictor has lower MAE than LoRA-D; '
           'frozen-D and W5-D are worse still.'),
    ('L4', 'The Koren survey gives weak rank agreement, negative for some substrates, on a '
           'different degron class, length and three-bin scale.'),
    ('L5', 'Positive-event calibration error of LoRA-D is worse than W5-D although its Brier '
           'score is better.'),
    ('L6', 'The negative direction stays weak and only 85 peptides are eligible for it.'),
    ('L7', 'Final predictions on W are in sample; the score shift is published and is not '
           'corrected using T.'),
    ('L8', 'One Koren substrate protein also occurs in the Zhang data, so the nine substrates '
           'are not fully independent.'),
    ('L9', 'The earlier verdict on the training-coverage family is unchanged; the LoRA result '
           'does not replace it.'),
    ('L10', 'Cross-runtime parity was outstanding when the decision was recorded, and no '
            'wet-lab or resource benefit of this project has been demonstrated.'),
]
lines = [PROVENANCE, r'{\small', r'\begin{longtable}{P{0.8cm}P{12.2cm}}',
         r'\caption{Limitations recorded with the scope decision}\label{tab:transfer-limits}\\',
         r'\toprule ID & Limitation \\', r'\midrule\endfirsthead',
         r'\caption[]{Limitations recorded with the scope decision (continued)}\\',
         r'\toprule ID & Limitation \\', r'\midrule\endhead']
lines += [f'{i} & {text} \\\\' for i, text in LIMITS]
lines += [r'\bottomrule', r'\end{longtable}}', '']
(HERE / 'tab-transfer-limits.tex').write_text('\n'.join(lines), encoding='utf-8')

# -------------------------------------------------------------------- macros
den = R['denominators']
cf, cw = R['contrasts'][CON_FROZEN], R['contrasts'][CON_W5]
gt5 = S['strata_lora_minus_zero']['gt5']
bottom = S['contrasts'][CON_FROZEN]['bins']['[0.0, 0.25)']
lat_ridge = L['m3-ext4.0-platt-v1']
lat_lora = L['esm2-35m-lora-d-aa4fc2b7']
macros = {
    'TCampaign': R['campaign'],
    'TCells': f"{den['cells']:,}",
    'TPeptides': f"{den['peptides']:,}",
    'TGroups': f"{den['groups']:,}",
    'TLoraMae': f(m[LORA]['all']['mae']),
    'TFrozenMae': f(m[FROZEN]['all']['mae']),
    'TWfiveMae': f(m[W5]['all']['mae']),
    'TZeroMae': f(m[ZERO]['all']['mae']),
    'TLoraAuc': f(m[LORA]['all']['auroc_plus']),
    'TLoraRho': f(m[LORA]['all']['spearman']),
    'TLoraAucMinus': f(m[LORA]['all']['auroc_minus']),
    'TMinusEligible': str(m[LORA]['all']['auroc_minus_eligible_peptides']),
    'TLoraBrier': f(R['probability_metrics'][LORA]['brier_three_class']),
    'TWfiveBrier': f(R['probability_metrics'][W5]['brier_three_class']),
    'TLoraEce': f(R['probability_metrics'][LORA]['plus']['ece']),
    'TWfiveEce': f(R['probability_metrics'][W5]['plus']['ece']),
    'TDeltaFrozen': f(cf['delta']),
    'TDeltaFrozenCI': ci(cf['ci_adjusted']),
    'TDeltaWfive': f(cw['delta']),
    'TDeltaWfiveCI': ci(cw['ci_adjusted']),
    'TBootstrap': f"{cf['bootstrap']:,}",
    'TGtFiveN': str(gt5['peptides']),
    'TGtFiveGroups': str(gt5['clusters']),
    'TGtFiveDelta': f(gt5['delta']),
    'TGtFiveCI': ci(gt5['ci_adjusted']),
    'TGtFiveZero': f(m[ZERO]['strata']['gt5']['mae']),
    'TGtFiveLora': f(m[LORA]['strata']['gt5']['mae']),
    'TGtFiveTarget': f(E['strata'][2]['target_mean'], 3),
    'TGtFivePred': f(E['strata'][2]['prediction_mean'], 3),
    'TBottomBinN': f"{bottom['peptides']:,}",
    'TBottomBinGroups': str(bottom['clusters']),
    'TBottomBinDelta': f(bottom['delta']),
    'TBottomBinCI': ci(bottom['ci_adjusted']),
    'TSimRho': f(S['contrasts'][CON_FROZEN]['spearman_identity_vs_delta']['rho'], 3),
    'TSimRhoP': f(S['contrasts'][CON_FROZEN]['spearman_identity_vs_delta']['pvalue'], 2),
    'TIdentityMin': f(bottom['min_identity'], 3),
    'TIdentityMax': f(S['contrasts'][CON_FROZEN]['bins']['[0.25, 0.5)']['max_identity'], 3),
    'TKorenSubstrates': str(K['denominator']['substrates']),
    'TKorenMutants': f"{K['denominator']['mutants']:,}",
    'TKorenLora': f(K['macro_spearman']['lora'], 3),
    'TKorenFrozen': f(K['macro_spearman']['frozen'], 3),
    'TModelCount': str(len(C['model_ids'])),
    'TAdapterRank': str(C['adapter']['rank']),
    'TAdapterAlpha': str(C['adapter']['alpha']),
    'TBaseRevision': C['base_revision'][:12],
    'TParityRows': str(C['parity']['tests'][0]['rows']),
    'TLatRidge': f(lat_ridge['p95_ms'], 1),
    'TLatLora': f(lat_lora['p95_ms'] / 1000.0, 1),
    'TLatRatio': f(lat_lora['p95_ms'] / lat_ridge['p95_ms'], 0),
    'TLatTarget': '300',
}
out = [PROVENANCE] + [r'\newcommand{\n' + k + '}{' + v + '}' for k, v in macros.items()] + ['']
(HERE / 'transfer-numbers.tex').write_text('\n'.join(out), encoding='utf-8')

# ------------------------------------------------------------------- figures
fig, axes = plt.subplots(1, 2, figsize=(11, 4.0))
ax = axes[0]
order = [LORA, FROZEN, W5, ZERO, CONST]
vals = [m[k]['all']['mae'] for k in order]
colours = [BLUE, ORANGE, GREEN, GRAY, GRAY]
bars = ax.barh([NAMES[k] for k in order][::-1], vals[::-1], color=colours[::-1], height=0.6)
for bar, value in zip(bars, vals[::-1]):
    ax.text(value + 0.004, bar.get_y() + bar.get_height() / 2, f'{value:.4f}',
            va='center', fontsize=11)
ax.set_xlabel('Peptide-macro MAE on T (PSI)')
ax.set_xlim(0, max(vals) * 1.18)
ax.set_title('(a) Transfer error', loc='left', fontsize=13)

ax = axes[1]
labels = ['LoRA-D\nminus frozen-D', 'LoRA-D\nminus W5-D']
deltas = [cf['delta'], cw['delta']]
lows = [d - c['ci_adjusted'][0] for d, c in zip(deltas, (cf, cw))]
highs = [c['ci_adjusted'][1] - d for d, c in zip(deltas, (cf, cw))]
ax.errorbar(deltas, [1, 0], xerr=[lows, highs], fmt='o', color=BLUE,
            capsize=5, markersize=7, linewidth=1.6)
ax.axvline(0, color=GRAY, linestyle='--', linewidth=1)
ax.set_yticks([1, 0])
ax.set_yticklabels(labels)
ax.set_xlabel('Change in MAE (PSI); negative favours LoRA-D')
ax.set_xlim(-0.065, 0.012)
ax.set_title('(b) Paired contrasts, adjusted intervals', loc='left', fontsize=13)
fig.tight_layout()
fig.savefig(HERE / 'fig-transfer-contrasts.pdf')
fig.savefig(HERE / 'fig-transfer-contrasts.png', dpi=200)
plt.close(fig)

