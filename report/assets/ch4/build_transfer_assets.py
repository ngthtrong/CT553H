ax = axes[0]
x = np.arange(len(STRATA))
for key, colour, marker in ((LORA, BLUE, 'o'), (FROZEN, ORANGE, 's'),
                            (W5, GREEN, '^'), (ZERO, GRAY, 'D')):
    ax.plot(x, [m[key]['strata'][s]['mae'] for s, _ in STRATA], marker=marker,
            color=colour, label=NAMES[key], linewidth=1.6, markersize=6)
ax.set_xticks(x)
ax.set_xticklabels([r'$\leq 3$', '3-4', '4-5', '> 5'])
ax.set_xlabel('Measured scanning WT PSI')
ax.set_ylabel('Peptide-macro MAE (PSI)')
ax.legend(frameon=False, fontsize=11)
ax.set_title('(a) Error by WT stability', loc='left', fontsize=13)

ax = axes[1]
deltas = [S['strata_lora_minus_zero'][s]['delta'] for s, _ in STRATA]
lo = [d - S['strata_lora_minus_zero'][s]['ci_adjusted'][0] for d, (s, _) in zip(deltas, STRATA)]
